import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import vm from 'node:vm';
const root=path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const read=async relative=>(await fs.readFile(path.join(root,relative),'utf8')).replace(/\r\n/g,'\n');
const lab=JSON.parse(await read('data/library.json')),atlas=JSON.parse(await read('data/songs.json'));
const views={};for(const view of['lab','songs'])views[view]={html:await read('src/views/'+view+'/template.html'),css:await read('src/views/'+view+'/style.css')};
const factory=(name,view,scripts,extra)=>`function ${name}(root,studio,seed${extra?',labStudies':''}){const document=studio.documentFor(root),window=studio.windowFor('${view}'),localStorage=studio.storageFor('${view}'),location=window.location,history=window.history;const ${view==='lab'?'SEED=seed':'ATLAS_SEED=seed,LAB_STUDIES=labStudies'};\n${scripts.join('\n')}\nreturn window.viewApi;}`;
const labFactory=factory('createLabView','lab',await Promise.all(['examples.js','bridge.js','app.js'].map(f=>read('src/views/lab/'+f))),false);
const songFactory=factory('createSongView','songs',[await read('src/views/songs/app.js')],true);
const seed={lab,atlas,views};
const js=[await read('src/harmony-core.js'),await read('src/atlas-core.js'),await read('src/store.js'),await read('src/routing.js'),await read('src/runtime.js'),labFactory,songFactory,await read('src/app.js')].join('\n');
new vm.Script(js,{filename:'harmony-studio.js'});
const html=(await read('src/index.html')).replace('/*STUDIO_STYLE*/',await read('src/style.css')).replace('/*STUDIO_DATA*/',JSON.stringify(seed).replace(/</g,'\\u003c')).replace('/*STUDIO_APP*/',js.replace(/<\/script/gi,'<\\/script'));
await fs.mkdir(path.join(root,'dist'),{recursive:true});
await fs.writeFile(path.join(root,'index.html'),html);
await fs.writeFile(path.join(root,'dist/index.html'),html);
await fs.writeFile(path.join(root,'.nojekyll'),'');
await fs.writeFile(path.join(root,'dist/.nojekyll'),'');
console.log(`Built index.html and dist/index.html (${Buffer.byteLength(html)} bytes). No external assets required.`);
